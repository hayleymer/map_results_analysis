CREATE TABLE map_data AS
SELECT
    term_name,
    subject,
	course,
	test_id,
	TO_DATE(test_start_date, 'MM/DD/YYYY') AS test_start_date,
	test_start_time::TIME AS test_start_time, 
	test_duration_minutes::INT AS test_duration,
	test_rit_score::INT AS test_rit_score,
	test_standard_error::NUMERIC AS test_standard_error,
	test_percentile::INT AS test_percentile,
	achievement_quintile, 
	percent_correct::INT AS percent_correct,
	rapid_guessing_percentage::NUMERIC AS rapid_guessing_percentage, 
	fall_to_fall_projected_growth::INT AS fall_to_fall_projected_growth,
	fall_to_fall_observed_growth::INT AS fall_to_fall_observed_growth,
	fall_to_fall_met_projected_growth, 
	fall_to_fall_conditional_growth_index::NUMERIC AS fall_to_fall_conditional_growth_index,
	fall_to_fall_conditional_growth_percentile::INT AS fall_to_fall_conditional_growth_percentile,
	fall_to_fall_growth_quintile,
	NULLIF(REGEXP_REPLACE(lexile_score, '[^0-9]', '', 'g'), '')::INT AS lexile_score,
	NULLIF(REGEXP_REPLACE(lexile_min, '[^0-9]', '', 'g'), '')::INT AS lexile_min,
	NULLIF(REGEXP_REPLACE(lexile_max, '[^0-9]', '', 'g'), '')::INT AS lexile_max,
	NULLIF(REGEXP_REPLACE(quantile_score, '[^0-9]', '', 'g'), '')::INT AS quantile_score,
	NULLIF(REGEXP_REPLACE(quantile_min, '[^0-9]', '', 'g'), '')::INT AS quantile_min,
	NULLIF(REGEXP_REPLACE(quantile_max, '[^0-9]', '', 'g'), '')::INT AS quantile_max,
 	goal1_name, 
	goal1_rit_score::INT AS goal1_rit_score,
	goal1_adjective, 
	goal2_name,
	goal2_rit_score::INT as goal2_rit_score, 
	goal2_adjective,
	goal3_name, 
	goal3_rit_score::INT as goal3_rit_score,
	goal3_adjective,
	goal4_name, 
	goal4_rit_score::INT as goal4_rit_score,
	goal4_adjective,
	projected_proficiency_study1, 
	projected_proficiency_level1, 
	projected_proficiency_study2,
	projected_proficiency_level2,
	projected_proficiency_study3,
	projected_proficiency_level3,
	grade::INT AS grade, 
	student_gender, 
	anon_student_id::INT AS student_id
FROM map_data_analysis;
